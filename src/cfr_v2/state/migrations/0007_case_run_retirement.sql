-- 0007 Retiring case runs (LDR-0045): hide runs from the Cases list, the exports and the counts,
-- and bring them back. Append-only like the rest: a run's latest row says whether it's retired.
CREATE TABLE case_run_retirement (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_run_id TEXT NOT NULL,
    retired BOOLEAN NOT NULL,                 -- true: retired; false: restored
    reason TEXT,                              -- a few words from whoever did it, never case text
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_case_run_retirement PRIMARY KEY (event_id),
    CONSTRAINT fk_case_run_retirement_case_run_id_case_run FOREIGN KEY (case_run_id) REFERENCES case_run (case_run_id),
    CONSTRAINT ck_case_run_retirement_reason CHECK (reason IS NULL OR length(reason) <= 200)
);
CREATE INDEX ix_case_run_retirement_case_run_id_event_id ON case_run_retirement (case_run_id, event_id DESC);

CREATE TRIGGER "case_run_retirement_append_only" BEFORE UPDATE OR DELETE ON case_run_retirement
    FOR EACH ROW EXECUTE FUNCTION cfr_reject_mutation();
CREATE TRIGGER "case_run_retirement_no_truncate" BEFORE TRUNCATE ON case_run_retirement
    FOR EACH STATEMENT EXECUTE FUNCTION cfr_reject_mutation();

-- The runs retired now, with when and why.
CREATE VIEW case_run_retired AS
SELECT case_run_id, created_at AS retired_at, reason FROM (
    SELECT DISTINCT ON (case_run_id) case_run_id, retired, created_at, reason
    FROM case_run_retirement ORDER BY case_run_id, event_id DESC
) latest
WHERE retired;
